/** One complete Concept identity, shown by src/components/brand-studio/CaseStudy.astro. */
export interface CaseStudy {
  id: 'pura' | 'latte';
  name: string;
  /** Tab label. */
  tab: string;
  /** The line after the name in the cover title. */
  kicker: string;
  tagline: string;
  /** Four short lines: the brief. */
  brief: { label: string; text: string }[];
  /** Photo used for the cover (file name without extension, in the study's folder). */
  cover: { photo: string; position: string };
  /** Palette: five colours with jobs. Contrast notes are computed at build time. */
  palette: { name: string; hex: string; role: string; use: string }[];
  /** Which colours sit where in the plates. */
  roles: { primary: string; light: string; accent: string; soft: string; dark: string };
  display: { id: string; family: string; weight: number; sample: string };
  body: { id: string; family: string; weight: number };
  /** Logomark crop (viewBox) and the clear-space unit "x" in logo units. */
  markBox: string;
  clearX: number;
  pattern: 'leaf' | 'mug';
  social: {
    photo: string;
    position: string;
    kicker: string;
    headline: string;
    bg: string;
    fg: string;
  }[];
  mockups: { photo: string; caption: string }[];
  /** Name for the minimum-size line. */
  minimum: { logoMm: number; logoPx: number; markMm: number; markPx: number };
}

